import { useSyncExternalStore } from "react";
import type { EngineStatus, ExportedFile, FeatureDraft, IpcResult, MateInput, SimParams } from "../shared/ipc";
import { bridge, engine, EngineRequestError, sessionOf, unwrap } from "./api";
import type { ExtrudeSpec, PreviewResult, RevisionSummary, SelectionInfo, SessionState, SimResult, SketchPlane, Vec3 } from "./types";

/** What the part sketcher is working on: a new sketch on a plane, or an
 * existing extrude feature being edited. */
export type SketchTarget = {
  plane: SketchPlane;
  featureId?: string;
  name?: string;
  material?: string | null;
  spec?: ExtrudeSpec;
};

export type Workspace = "model" | "sketch" | "drawing" | "fab" | "simulate";
export type PickMode = "part" | "face" | "edge";
/** A face or edge the user clicked, with the world point under the cursor. */
export type TopoPick = { component: string; kind: "face" | "edge"; id: string; point: Vec3 };
export type ViewName = "iso" | "top" | "front" | "right";
export type Tool = "select" | "measure" | "move";
export type LogEntry = { id: number; level: "info" | "error"; text: string; at: Date; path?: string };

export type AppState = {
  engine: EngineStatus;
  session: SessionState | null;
  selection: SelectionInfo | null;
  selectedId: string | null;
  hovered: string | null;
  workspace: Workspace;
  tool: Tool;
  view: { name: ViewName; nonce: number };
  ortho: boolean;
  fitNonce: number;
  /** Bumped to frame everything without changing the view direction. */
  fitAll: number;
  pending: number;
  paramErrors: Record<string, string>;
  history: RevisionSummary[];
  log: LogEntry[];
  /** Feature ids regenerated by the last rebuild, for the tree highlight. */
  regenerated: string[];
  pickMode: PickMode;
  /** Face/edge picks; shift-click adds. */
  picks: TopoPick[];
  hoverTopo: TopoPick | null;
  /** Uncommitted feature shown in the viewport. */
  preview: PreviewResult | null;
  showMass: boolean;
  sim: SimResult | null;
  simTime: number;
  simPlaying: boolean;
  simRunning: boolean;
  sketchTarget: SketchTarget | null;
};

let state: AppState = {
  engine: { state: "starting" },
  session: null,
  selection: null,
  selectedId: null,
  hovered: null,
  workspace: "model",
  tool: "select",
  view: { name: "iso", nonce: 0 },
  ortho: false,
  fitNonce: 0,
  fitAll: 0,
  pending: 0,
  paramErrors: {},
  history: [],
  log: [],
  regenerated: [],
  pickMode: "part",
  picks: [],
  hoverTopo: null,
  preview: null,
  showMass: false,
  sim: null,
  simTime: 0,
  simPlaying: false,
  simRunning: false,
  sketchTarget: null,
};

const listeners = new Set<() => void>();
let logId = 0;

export function getState(): AppState {
  return state;
}

export function setState(patch: Partial<AppState> | ((s: AppState) => Partial<AppState>)): void {
  const next = typeof patch === "function" ? patch(state) : patch;
  state = { ...state, ...next };
  for (const l of listeners) l();
}

/**
 * Subscribes to a slice of state. Selectors must return stable references
 * (no fresh arrays/objects per call) or React will re-render forever.
 */
export function useApp<T>(select: (s: AppState) => T): T {
  return useSyncExternalStore(
    (l) => {
      listeners.add(l);
      return () => listeners.delete(l);
    },
    () => select(state),
  );
}

export function log(level: LogEntry["level"], text: string, path?: string): void {
  setState((s) => ({ log: [{ id: ++logId, level, text, at: new Date(), path }, ...s.log].slice(0, 200) }));
}

function message(err: unknown): string {
  return err instanceof Error ? err.message : String(err);
}

/** Applies a session if it is not older than what is on screen. */
export function applySession(session: SessionState | null): void {
  if (!session) return;
  const current = state.session?.document.revision ?? -1;
  if (session.document.revision < current) return;
  const opened = !state.session || state.session.document.project.id !== session.document.project.id;
  const selectedId =
    state.selectedId && session.document.components.some((c) => c.id === state.selectedId) ? state.selectedId : null;
  // Picks survive a rebuild only while their face/edge still exists.
  const meshes = new Map(session.document.scene.meshes.map((m) => [m.component_id, m]));
  const picks = state.picks.filter((p) => {
    const m = meshes.get(p.component);
    return m ? (p.kind === "face" ? m.faces.some((f) => f.id === p.id) : m.edge_info.some((e) => e.id === p.id)) : false;
  });
  setState((s) => ({
    session,
    selectedId,
    picks: picks.length === s.picks.length ? s.picks : picks,
    selection: selectedId ? s.selection : null,
    regenerated: session.rebuild.regenerated,
    fitNonce: opened ? s.fitNonce + 1 : s.fitNonce,
    // A simulation describes the design it ran on.
    sim: s.session && s.session.document.revision !== session.document.revision ? null : s.sim,
  }));
  if (selectedId) void refreshSelection(selectedId);
  void refreshHistory();
}

async function refreshSelection(id: string): Promise<void> {
  try {
    const info = await engine.select(id);
    if (state.selectedId === id) setState({ selection: info });
  } catch {
    /* the next session will settle it */
  }
}

export async function refreshHistory(): Promise<void> {
  try {
    setState({ history: await engine.history(40) });
  } catch {
    /* history is optional */
  }
}

/** Runs a model edit. Errors land in the log and, for parameters, inline. */
export async function mutate(
  label: string,
  work: () => Promise<SessionState | null>,
  param?: string,
): Promise<boolean> {
  setState((s) => ({ pending: s.pending + 1 }));
  try {
    applySession(await work());
    if (param) setState((s) => ({ paramErrors: { ...s.paramErrors, [param]: "" } }));
    return true;
  } catch (err) {
    const text = message(err);
    if (param) setState((s) => ({ paramErrors: { ...s.paramErrors, [param]: text } }));
    log("error", `${label}: ${text}`);
    return false;
  } finally {
    setState((s) => ({ pending: s.pending - 1 }));
  }
}

export const actions = {
  setParameter: (name: string, value: number) => mutate(`set ${name}`, () => engine.setParameter(name, value), name),
  setMaterial: (feature: string, material: string) => mutate(`material ${feature}`, () => engine.setMaterial(feature, material)),
  setSuppressed: (feature: string, suppressed: boolean) =>
    mutate(`${suppressed ? "suppress" : "unsuppress"} ${feature}`, () => engine.setSuppressed(feature, suppressed)),
  movePart: (id: string, offset: [number, number, number]) => mutate(`move ${id}`, () => engine.movePart(id, offset)),
  undo: () => mutate("undo", () => engine.undo()),
  redo: () => mutate("redo", () => engine.redo()),
  restore: (revision: number) => mutate(`restore ${revision}`, () => engine.restore(revision)),

  addFeature: (draft: FeatureDraft) => mutate(`add ${draft.name}`, () => engine.addFeature(draft)),
  editFeature: (id: string, draft: FeatureDraft) => mutate(`edit ${draft.name}`, () => engine.editFeature(id, draft)),
  deleteFeature: (id: string) => mutate(`delete ${id}`, () => engine.deleteFeature(id)),
  addMate: (mate: MateInput) => mutate(`add ${mate.name}`, () => engine.addMate(mate)),
  deleteMate: (id: string) => mutate(`delete ${id}`, () => engine.deleteMate(id)),

  /** Shows a draft without committing it. Errors stay in the preview. */
  async preview(draft: FeatureDraft | null): Promise<PreviewResult | null> {
    if (!draft) {
      setState({ preview: null });
      return null;
    }
    try {
      const result = await engine.previewFeature(draft);
      setState({ preview: result });
      return result;
    } catch (err) {
      const result: PreviewResult = {
        meshes: [],
        mass: null,
        diagnostics: [{ severity: "error", code: "DRAFT", message: message(err), related_ids: [], source: "feature" }],
      };
      setState({ preview: result });
      return result;
    }
  },

  async simulate(params: SimParams): Promise<boolean> {
    setState({ simRunning: true });
    try {
      const sim = await engine.simulate(params);
      setState({ sim, simTime: 0, simPlaying: true });
      const s = sim.summary;
      log(
        "info",
        `simulated ${params.duration_s} s: heave ${s.max_heave_in.toFixed(1)} in, roll ${s.max_roll_deg.toFixed(1)} deg, pitch ${s.max_pitch_deg.toFixed(1)} deg, min freeboard ${s.min_freeboard_in.toFixed(1)} in`,
      );
      return true;
    } catch (err) {
      log("error", `simulate: ${message(err)}`);
      return false;
    } finally {
      setState({ simRunning: false });
    }
  },

  pick(pick: TopoPick | null, additive: boolean): void {
    if (!pick) {
      if (!additive) setState({ picks: [] });
      return;
    }
    setState((s) => {
      const same = (p: TopoPick) => p.component === pick.component && p.kind === pick.kind && p.id === pick.id;
      const picks = additive ? (s.picks.some(same) ? s.picks.filter((p) => !same(p)) : [...s.picks, pick]) : [pick];
      return { picks };
    });
    if (state.selectedId !== pick.component) void actions.select(pick.component);
  },

  async select(id: string | null): Promise<void> {
    setState({ selectedId: id, selection: id === state.selectedId ? state.selection : null });
    try {
      const info = await engine.select(id);
      if (state.selectedId === id) setState({ selection: info });
    } catch (err) {
      log("error", `select: ${message(err)}`);
    }
  },

  async openSample(): Promise<void> {
    await runFile("open sample", () => bridge().openSample());
  },
  async openProject(): Promise<void> {
    await runFile("open", () => bridge().openProject());
  },
  async save(asNew = false): Promise<void> {
    try {
      const result = await (asNew ? bridge().saveProjectAs() : bridge().saveProject());
      if (!result) return;
      const { path } = unwrap(result);
      log("info", `saved ${path}`, path);
      const session = await engine.document();
      if (session) setState({ session: { ...session } });
    } catch (err) {
      log("error", `save: ${message(err)}`);
    }
  },
  async exportFile(format: "dxf" | "step" | "pdf" | "csv"): Promise<void> {
    try {
      const result = await bridge().exportFile(format);
      if (!result) return;
      const file = unwrap(result);
      log("info", `exported ${format.toUpperCase()} ${formatBytes(file.bytes)} to ${file.path}`, file.path);
    } catch (err) {
      log("error", `export ${format}: ${message(err)}`);
    }
  },
  async exportAll(): Promise<void> {
    try {
      const result = await bridge().exportAll();
      if (!result) return;
      for (const file of unwrap(result) as ExportedFile[]) {
        log("info", `exported ${file.format.toUpperCase()} ${formatBytes(file.bytes)} to ${file.path}`, file.path);
      }
    } catch (err) {
      log("error", `export: ${message(err)}`);
    }
  },
};

async function runFile(label: string, work: () => Promise<IpcResult<unknown> | null>): Promise<void> {
  setState((s) => ({ pending: s.pending + 1 }));
  try {
    const result = await work();
    if (!result) return;
    handlePushed(result);
  } catch (err) {
    log("error", `${label}: ${message(err)}`);
  } finally {
    setState((s) => ({ pending: s.pending - 1 }));
  }
}

/** Sessions from file commands (button or native menu). */
export function handlePushed(result: IpcResult<unknown>): void {
  try {
    const session = sessionOf(unwrap(result));
    if (!session) return;
    setState({ session: null, selectedId: null, selection: null, paramErrors: {} });
    applySession(session);
    log("info", `opened ${session.document.project.name} (${session.document.components.length} parts)`);
  } catch (err) {
    log("error", err instanceof EngineRequestError ? `${err.code}: ${err.message}` : message(err));
  }
}

export function formatBytes(bytes: number): string {
  if (bytes < 1024) return `${bytes} B`;
  if (bytes < 1024 * 1024) return `${(bytes / 1024).toFixed(1)} KB`;
  return `${(bytes / 1024 / 1024).toFixed(2)} MB`;
}
