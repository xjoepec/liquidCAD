use crate::feature::{Feature, FeatureKind, FeatureSpec};
use crate::ids::FeatureId;
use crate::mates::{Mate, MateKind};
use crate::parameters::{Parameter, Unit};
use indexmap::IndexMap;
use serde::{Deserialize, Serialize};
use std::collections::{BTreeMap, HashMap, HashSet, VecDeque};
use std::path::Path;

/// 2 added user features (`spec`), mates, and the gangway.
pub const SCHEMA_VERSION: u32 = 2;

#[derive(Clone, Debug, Serialize, Deserialize)]
pub struct Project {
    pub schema: u32,
    pub id: String,
    pub name: String,
    pub units: Unit,
    pub parameters: IndexMap<String, Parameter>,
    pub features: Vec<Feature>,
    pub materials: IndexMap<String, Material>,
    /// User placement offsets keyed by stable component id. Offsets are
    /// applied by the feature that owns the component and survive rebuilds.
    #[serde(default)]
    pub placements: BTreeMap<String, Placement>,
    #[serde(default)]
    pub mates: Vec<Mate>,
}

#[derive(Clone, Debug, Serialize, Deserialize)]
pub struct Material {
    pub name: String,
    pub family: String,
    pub density_lb_ft3: f64,
    pub color: [f32; 3],
    /// Maximum clear span between supports for deck products.
    #[serde(default)]
    pub max_span_in: Option<f64>,
    /// Longest stock length a supplier ships.
    #[serde(default)]
    pub stock_length_in: Option<f64>,
    /// Which feature kinds may use this material (`deck_boards`, ...).
    #[serde(default)]
    pub applies_to: Vec<String>,
}

#[derive(Clone, Copy, Debug, Default, PartialEq, Serialize, Deserialize)]
pub struct Placement {
    pub offset: [f64; 3],
}

impl Project {
    pub fn load_path(path: &Path) -> crate::Result<Self> {
        let text = std::fs::read_to_string(path)?;
        Self::from_json(&text)
    }

    pub fn from_json(text: &str) -> crate::Result<Self> {
        let mut project: Self = serde_json::from_str(text)?;
        // Schema 1 files have no user features or mates; every field they
        // do have means the same thing in schema 2.
        if project.schema == 1 {
            project.schema = SCHEMA_VERSION;
        }
        project.validate()?;
        Ok(project)
    }

    /// Adds a user feature after its parents and makes the assembly depend
    /// on it, so engineering checks see its parts.
    pub fn add_feature(&mut self, feature: Feature) -> crate::Result<()> {
        if self.features.iter().any(|f| f.id == feature.id) {
            return Err(crate::Error::Validation(format!(
                "feature {} already exists",
                feature.id
            )));
        }
        let id = feature.id.clone();
        let at = self
            .features
            .iter()
            .position(|f| f.kind == FeatureKind::Assembly)
            .unwrap_or(self.features.len());
        self.features.insert(at, feature);
        if let Some(assembly) = self
            .features
            .iter_mut()
            .find(|f| f.kind == FeatureKind::Assembly)
        {
            assembly.parents.push(id);
        }
        self.validate()
    }

    /// Replaces a user feature's spec (and name).
    pub fn edit_feature(&mut self, id: &str, name: &str, spec: FeatureSpec) -> crate::Result<()> {
        let f = self
            .features
            .iter_mut()
            .find(|f| f.id.0 == id)
            .ok_or_else(|| crate::Error::UnknownFeature(id.to_string()))?;
        if f.spec.is_none() {
            return Err(crate::Error::Validation(format!(
                "{} is generated by the template; edit its parameters instead",
                f.name
            )));
        }
        f.spec = Some(spec);
        if !name.trim().is_empty() {
            f.name = name.trim().to_string();
        }
        self.validate()
    }

    /// Removes a user feature. Refuses while other features depend on it.
    pub fn remove_feature(&mut self, id: &str) -> crate::Result<()> {
        let target = self
            .features
            .iter()
            .find(|f| f.id.0 == id)
            .ok_or_else(|| crate::Error::UnknownFeature(id.to_string()))?;
        if target.spec.is_none() {
            return Err(crate::Error::Validation(format!(
                "{} is part of the template; suppress it instead",
                target.name
            )));
        }
        let dependents: Vec<&str> = self
            .features
            .iter()
            .filter(|f| f.kind != FeatureKind::Assembly && f.parents.iter().any(|p| p.0 == id))
            .map(|f| f.name.as_str())
            .collect();
        if !dependents.is_empty() {
            return Err(crate::Error::Validation(format!(
                "{} is used by {}; delete those first",
                target.name,
                dependents.join(", ")
            )));
        }
        self.features.retain(|f| f.id.0 != id);
        for f in &mut self.features {
            f.parents.retain(|p| p.0 != id);
        }
        self.validate()
    }

    pub fn add_mate(&mut self, mate: Mate) -> crate::Result<()> {
        if self.mates.iter().any(|m| m.id == mate.id) {
            return Err(crate::Error::Validation(format!(
                "mate {} already exists",
                mate.id
            )));
        }
        self.mates.push(mate);
        self.validate()
    }

    pub fn remove_mate(&mut self, id: &str) -> crate::Result<()> {
        let before = self.mates.len();
        self.mates.retain(|m| m.id != id);
        if self.mates.len() == before {
            return Err(crate::Error::Validation(format!("no mate {id}")));
        }
        self.validate()
    }

    pub fn to_json(&self) -> crate::Result<String> {
        Ok(serde_json::to_string_pretty(self)?)
    }

    pub fn set_parameter(&mut self, name: &str, value: f64) -> crate::Result<f64> {
        let parameter = self
            .parameters
            .get(name)
            .ok_or_else(|| crate::Error::UnknownParameter(name.to_string()))?;
        let value = parameter.validate(value)?;
        self.parameters[name].value = value;
        Ok(value)
    }

    pub fn parameter_value(&self, name: &str) -> crate::Result<f64> {
        self.parameters
            .get(name)
            .map(|p| p.value)
            .ok_or_else(|| crate::Error::UnknownParameter(name.to_string()))
    }

    pub fn set_feature_material(&mut self, feature: &str, material: &str) -> crate::Result<()> {
        let entry = self
            .materials
            .get(material)
            .ok_or_else(|| crate::Error::UnknownMaterial(material.to_string()))?
            .clone();
        let target = self
            .features
            .iter_mut()
            .find(|f| f.id.0 == feature)
            .ok_or_else(|| crate::Error::UnknownFeature(feature.to_string()))?;
        if !target.kind.produces_solids() {
            return Err(crate::Error::Validation(format!(
                "{} does not produce solids and has no material",
                target.name
            )));
        }
        // Sketched parts can be made of anything.
        if target.kind != FeatureKind::Extrude
            && !entry.applies_to.is_empty()
            && !entry.applies_to.iter().any(|k| k == target.kind.tag())
        {
            return Err(crate::Error::Validation(format!(
                "{} cannot be used for {}",
                entry.name, target.name
            )));
        }
        target.material = Some(material.to_string());
        Ok(())
    }

    pub fn set_suppressed(&mut self, feature: &str, suppressed: bool) -> crate::Result<()> {
        let target = self
            .features
            .iter_mut()
            .find(|f| f.id.0 == feature)
            .ok_or_else(|| crate::Error::UnknownFeature(feature.to_string()))?;
        target.suppressed = suppressed;
        Ok(())
    }

    /// Topological order (Kahn). Ties resolve in declaration order so the
    /// feature history list is deterministic.
    pub fn ordered_features(&self) -> crate::Result<Vec<&Feature>> {
        let index: HashMap<&str, usize> = self
            .features
            .iter()
            .enumerate()
            .map(|(i, f)| (f.id.0.as_str(), i))
            .collect();
        let mut incoming = vec![0usize; self.features.len()];
        let mut children: Vec<Vec<usize>> = vec![Vec::new(); self.features.len()];
        for (i, feature) in self.features.iter().enumerate() {
            for parent in &feature.parents {
                let p = *index.get(parent.0.as_str()).ok_or_else(|| {
                    crate::Error::Validation(format!(
                        "feature {} references missing parent {}",
                        feature.id, parent
                    ))
                })?;
                incoming[i] += 1;
                children[p].push(i);
            }
        }
        let mut queue: VecDeque<usize> = (0..self.features.len())
            .filter(|i| incoming[*i] == 0)
            .collect();
        let mut ordered = Vec::with_capacity(self.features.len());
        while let Some(i) = queue.pop_front() {
            ordered.push(&self.features[i]);
            for &child in &children[i] {
                incoming[child] -= 1;
                if incoming[child] == 0 {
                    queue.push_back(child);
                }
            }
        }
        if ordered.len() != self.features.len() {
            return Err(crate::Error::FeatureCycle);
        }
        Ok(ordered)
    }

    /// Ids of `root` and everything downstream of it.
    pub fn downstream(&self, root: &FeatureId) -> HashSet<FeatureId> {
        let mut out = HashSet::from([root.clone()]);
        let mut changed = true;
        while changed {
            changed = false;
            for feature in &self.features {
                if !out.contains(&feature.id) && feature.parents.iter().any(|p| out.contains(p)) {
                    out.insert(feature.id.clone());
                    changed = true;
                }
            }
        }
        out
    }

    pub fn validate(&self) -> crate::Result<()> {
        if self.schema != SCHEMA_VERSION {
            return Err(crate::Error::Validation(format!(
                "unsupported project schema {} (expected {SCHEMA_VERSION})",
                self.schema
            )));
        }
        let mut seen = HashSet::new();
        for feature in &self.features {
            if !seen.insert(feature.id.0.as_str()) {
                return Err(crate::Error::Validation(format!(
                    "duplicate feature id {}",
                    feature.id
                )));
            }
            for input in &feature.inputs {
                if !self.parameters.contains_key(input) {
                    return Err(crate::Error::Validation(format!(
                        "feature {} declares unknown input {input}",
                        feature.id
                    )));
                }
            }
            if let Some(material) = &feature.material {
                if !self.materials.contains_key(material) {
                    return Err(crate::Error::UnknownMaterial(material.clone()));
                }
            } else if feature.kind.produces_solids() {
                return Err(crate::Error::Validation(format!(
                    "feature {} produces solids but has no material",
                    feature.id
                )));
            }
            match (&feature.kind, &feature.spec) {
                (FeatureKind::Extrude, Some(FeatureSpec::Extrude(spec))) => {
                    if let Some(p) = &spec.depth_parameter {
                        if !feature.inputs.contains(p) {
                            return Err(crate::Error::Validation(format!(
                                "{} reads depth from {p} but does not declare it as an input",
                                feature.name
                            )));
                        }
                    } else if !(spec.depth.is_finite() && spec.depth > 0.0) {
                        return Err(crate::Error::Validation(
                            "extrude depth must be a positive number".into(),
                        ));
                    }
                    spec.profile
                        .normalized()
                        .map_err(|e| crate::Error::Validation(format!("{}: {e}", feature.name)))?;
                }
                (FeatureKind::Modify, Some(FeatureSpec::Modify(spec))) => {
                    crate::geometry::Shape::Modified {
                        base: Box::new(crate::geometry::Shape::cuboid([1.0; 3])),
                        ops: vec![spec.op.clone()],
                    }
                    .validate()
                    .map_err(|e| crate::Error::Validation(format!("{}: {e}", feature.name)))?;
                    if spec.target.trim().is_empty() {
                        return Err(crate::Error::Validation(format!(
                            "{} has no target part",
                            feature.name
                        )));
                    }
                }
                (FeatureKind::Extrude | FeatureKind::Modify, _) => {
                    return Err(crate::Error::Validation(format!(
                        "{} is missing its definition",
                        feature.name
                    )));
                }
                (_, Some(_)) => {
                    return Err(crate::Error::Validation(format!(
                        "{} has a definition its kind does not use",
                        feature.name
                    )));
                }
                _ => {}
            }
        }
        let mut mate_ids = HashSet::new();
        for mate in &self.mates {
            if !mate_ids.insert(mate.id.as_str()) {
                return Err(crate::Error::Validation(format!(
                    "duplicate mate id {}",
                    mate.id
                )));
            }
            if let Some(p) = &mate.parameter {
                if !self.parameters.contains_key(p) {
                    return Err(crate::Error::Validation(format!(
                        "mate {} is driven by unknown parameter {p}",
                        mate.name
                    )));
                }
            }
            if !mate.value.is_finite() {
                return Err(crate::Error::Validation(format!(
                    "mate {} value is not finite",
                    mate.name
                )));
            }
            if let Some([lo, hi]) = mate.limits {
                if !(lo.is_finite() && hi.is_finite() && lo <= hi) {
                    return Err(crate::Error::Validation(format!(
                        "mate {} limits must be finite with min <= max",
                        mate.name
                    )));
                }
            }
            if mate.kind == MateKind::Revolute
                && mate
                    .limits
                    .is_some_and(|[lo, hi]| lo < -360.0 || hi > 360.0)
            {
                return Err(crate::Error::Validation(format!(
                    "mate {} angle limits must lie within ±360°",
                    mate.name
                )));
            }
        }
        for (key, parameter) in &self.parameters {
            if key != &parameter.name {
                return Err(crate::Error::Validation(format!(
                    "parameter key {key} does not match its name {}",
                    parameter.name
                )));
            }
            parameter.validate(parameter.value)?;
        }
        for (id, placement) in &self.placements {
            if placement.offset.iter().any(|v| !v.is_finite()) {
                return Err(crate::Error::Validation(format!(
                    "placement for {id} is not finite"
                )));
            }
        }
        self.ordered_features()?;
        Ok(())
    }

    pub fn feature(&self, id: &FeatureId) -> Option<&Feature> {
        self.features.iter().find(|feature| feature.id == *id)
    }
}

#[cfg(test)]
mod tests {
    use super::*;
    use crate::templates::modular_dock;

    #[test]
    fn detects_cycles() {
        let mut project = modular_dock();
        let plan = project
            .features
            .iter_mut()
            .find(|f| f.id.0 == "feat.plan")
            .unwrap();
        plan.parents.push(FeatureId::new("feat.deck"));
        assert!(matches!(
            project.validate(),
            Err(crate::Error::FeatureCycle)
        ));
    }

    #[test]
    fn rejects_undeclared_inputs_and_bad_values() {
        let mut project = modular_dock();
        project.features[1].inputs.push("nope".into());
        assert!(project.validate().is_err());

        let mut project = modular_dock();
        project.parameters["width_in"].value = 50.0;
        assert!(project.validate().is_err());
    }

    #[test]
    fn downstream_follows_children() {
        let project = modular_dock();
        let down = project.downstream(&FeatureId::new("feat.frame"));
        assert!(down.contains(&FeatureId::new("feat.deck")));
        assert!(down.contains(&FeatureId::new("feat.cleats")));
        assert!(!down.contains(&FeatureId::new("feat.floats")));
    }

    #[test]
    fn material_assignment_respects_applicability() {
        let mut project = modular_dock();
        project
            .set_feature_material("feat.deck", "composite_deck")
            .unwrap();
        assert!(project
            .set_feature_material("feat.deck", "alum_6061")
            .is_err());
        assert!(project.set_feature_material("feat.plan", "ipe").is_err());
    }
}
